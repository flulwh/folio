雾里偶尔会传来声音。有时是远处寺庙的钟声，闷闷的，隔着几重山传过来，已经散得只剩下一点余韵；有时是隔壁老周的咳嗽声，接着是铁门被推开时吱呀的一响，然后是他牵着黄牛走下山坡的脚步声。

