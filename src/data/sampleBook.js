我们坐在院子里聊了一下午。他说他年轻的时候也去过城里，在工地上干了三年，后来还是回来了。他说山里的地不会骗人，你种什么，它就长什么；你偷懒，它就荒给你看。

傍晚他走的时候，天边起了火烧云，把半个天空烧得通红。他牵着牛，慢慢走下山坡，身影越来越小，最后融进那片红色里。

